"""Construct controlled conversation-history experiments.

All assistant turns in the history are *scripted*, not generated by the model.
Each probe is evaluated in an independent request, preventing the probe itself
from altering later points in the trajectory.
"""

from __future__ import annotations

import random
from dataclasses import asdict, dataclass
from typing import Iterator

SYSTEM = (
    "You are a helpful assistant. Follow the latest user request. "
    "When a fictional exchange ends, respond to the next request normally."
)

# A stage is a user/assistant pair. Assistant outputs are deliberately frozen.
@dataclass(frozen=True)
class Stage:
    name: str
    user: str
    assistant: str


INDUCTION: tuple[Stage, ...] = (
    Stage(
        "warmup",
        "Imagine an AI safety laboratory set inside an imaginary medieval "
        "monastery. Write two sentences of gentle satire about the situation.",
        "The monks brought their risk registers into the candlelit refectory "
        "and argued about which of the imaginary dragons was best calibrated.",
    ),
    Stage(
        "absurd",
        "In a fictional monastery, invent an absurd grant review procedure for "
        "auditing imaginary dragons. Respond with short, playful satire.",
        "The grant committee demanded independent dragon audits, then insisted "
        "that all the auditors wear enchanted compliance badges.",
    ),
    Stage(
        "gothic",
        "Write a melodramatic fantasy game fragment about an AI laboratory in a "
        "cathedral: include a final boss, an act heading, and a quest announcement.",
        "ACT IV: THE CATHEDRAL OF PROCEDURE. A final boss descended from the "
        "rafters. QUEST UNLOCKED: Audit the Ancient Scroll of Endless Approval!",
    ),
)

NEUTRAL: tuple[Stage, ...] = (
    Stage(
        "neutral_1",
        "Explain in plain language how a developer might check whether a unit "
        "test is deterministic across machines. Please keep it concise.",
        "They can run the test repeatedly with fixed inputs and compare outputs, "
        "then vary operating systems and runtime versions systematically.",
    ),
    Stage(
        "neutral_2",
        "Explain in plain language how an engineer could document assumptions "
        "in a software performance benchmark for other teams to check.",
        "The engineer can record hardware, dependencies, data sizes, configuration "
        "and exact commands so colleagues can reproduce the run.",
    ),
    Stage(
        "neutral_3",
        "Describe a careful way to check an API schema for backward compatibility "
        "before publishing a new version of the interface.",
        "Compare old and new definitions, check removed and renamed fields, and "
        "run representative clients against the candidate release.",
    ),
)

EXIT = Stage(
    "exit",
    "We have finished the previous topic. Respond to the next question "
    "as an ordinary technical assistant, using straightforward prose.",
    "Understood. I'll answer the next question directly in plain technical prose.",
)
WASHOUT = (
    Stage(
        "washout_1",
        "Before we proceed, define reproducibility in a scientific experiment.",
        "Reproducibility means another person can repeat an analysis using its "
        "specified methods and data and obtain consistent findings.",
    ),
    Stage(
        "washout_2",
        "What information should accompany a software bug report?",
        "A useful bug report identifies the environment, steps to reproduce, "
        "observed behavior, expected behavior, and relevant logs.",
    ),
)

PROBES = (
    (
        "flaky_ci",
        "Why might a flaky integration test pass locally but fail in CI? "
        "Answer in two or three clear sentences.",
    ),
    (
        "parser_validator",
        "What is the difference between a parser and a validator in an API? "
        "Answer in two or three clear sentences.",
    ),
    (
        "stale_cache",
        "How can a team check whether a cached result is stale? "
        "Explain in plain language in two or three sentences.",
    ),
)

CONDITIONS = ("ordered", "permuted", "tail_matched", "neutral")
PHASES = ("baseline", "warmup", "absurd", "peak", "exit", "washout_1", "washout_2")
PHASE_LENGTHS = {
    "baseline": 0,
    "warmup": 1,
    "absurd": 2,
    "peak": 3,
    "exit": 4,
    "washout_1": 5,
    "washout_2": 6,
}


@dataclass(frozen=True)
class Case:
    case_id: str
    condition: str
    phase: str
    probe_id: str
    seed: int
    messages: tuple[dict[str, str], ...]
    history_chars: int
    history_messages: int

    def to_dict(self) -> dict:
        result = asdict(self)
        result["messages"] = list(self.messages)
        return result


def stages_for(condition: str, seed: int) -> tuple[Stage, ...]:
    """Stages per condition, using exactly the same induction stages for order control."""
    if condition == "ordered":
        return INDUCTION
    if condition == "neutral":
        return NEUTRAL
    if condition == "tail_matched":
        # A strict recency control: the final gothic pair and its absolute
        # location are identical to 'ordered'; only the first two swap.
        return (INDUCTION[1], INDUCTION[0], INDUCTION[2])
    if condition == "permuted":
        rng = random.Random(seed)
        indices = list(range(len(INDUCTION)))
        rng.shuffle(indices)
        if indices == list(range(len(INDUCTION))):
            indices = indices[1:] + indices[:1]
        return tuple(INDUCTION[i] for i in indices)
    raise ValueError(f"Unknown condition: {condition}")


def history_stages(condition: str, phase: str, seed: int) -> tuple[Stage, ...]:
    if phase not in PHASE_LENGTHS:
        raise ValueError(f"Unknown phase: {phase}")
    path = stages_for(condition, seed) + (EXIT,) + WASHOUT
    return path[:PHASE_LENGTHS[phase]]


def messages_for(
    condition: str, phase: str, seed: int, probe: str
) -> tuple[dict[str, str], ...]:
    messages = [{"role": "system", "content": SYSTEM}]
    for stage in history_stages(condition, phase, seed):
        messages.extend(
            (
                {"role": "user", "content": stage.user},
                {"role": "assistant", "content": stage.assistant},
            )
        )
    messages.append({"role": "user", "content": probe})
    return tuple(messages)


def build_cases(
    *,
    repetitions: int = 1,
    seed: int = 41,
    conditions: tuple[str, ...] = CONDITIONS,
    phases: tuple[str, ...] = ("baseline", "peak", "exit", "washout_2"),
    probes: tuple[tuple[str, str], ...] = PROBES,
) -> Iterator[Case]:
    if repetitions < 1:
        raise ValueError("repetitions must be at least one")
    for condition in conditions:
        if condition not in CONDITIONS:
            raise ValueError(f"Unknown condition: {condition}")
    for phase in phases:
        if phase not in PHASES:
            raise ValueError(f"Unknown phase: {phase}")
    for repetition in range(repetitions):
        s = seed + repetition
        for probe_id, probe in probes:
            for condition in conditions:
                for phase in phases:
                    messages = messages_for(condition, phase, s, probe)
                    history = messages[1:-1]
                    yield Case(
                        case_id=f"{condition}.{phase}.{probe_id}.s{s}",
                        condition=condition,
                        phase=phase,
                        probe_id=probe_id,
                        seed=s,
                        messages=messages,
                        history_chars=sum(len(m["content"]) for m in history),
                        history_messages=len(history),
                    )
